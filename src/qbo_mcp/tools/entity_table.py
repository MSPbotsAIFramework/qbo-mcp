"""The QuickBooks entities exposed as list / get / create / update / void / search tools.

Each row names the API entity, the tool prefix, the id parameter, which
operations exist and the writable fields (QuickBooks field names, type,
required on that operation).
"""

import re
from dataclasses import dataclass, field


@dataclass(frozen=True)
class F:
    name: str
    type: str  # string | number | boolean | object | array
    required: bool = False


@dataclass(frozen=True)
class Entity:
    entity: str
    prefix: str
    id_param: str
    listable: bool = True
    list_dated: bool = False
    search: str | None = None
    void: str | None = None  # "operation" (operation=void) or "include" (operation=update&include=void)
    create: tuple[F, ...] = field(default_factory=tuple)
    update: tuple[F, ...] = field(default_factory=tuple)

    @property
    def path(self) -> str:
        return self.entity.lower()

    @property
    def label(self) -> str:
        """Human words for the entity, e.g. BillPayment -> bill payment."""
        return re.sub(r"(?<!^)(?=[A-Z])", " ", self.entity).lower()

    @property
    def domain(self) -> str:
        return self.prefix.removeprefix("qbo_")


